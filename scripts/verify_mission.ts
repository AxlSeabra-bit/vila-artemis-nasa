import assert from 'node:assert/strict';
import { ArtemisEngine } from '../src/engine';
import { FLIGHT_DURATION_SEC } from '../src/expedition';
import { SAVE_STORAGE_KEY } from '../src/constants';
import { landOnMoon } from './mission-test-helpers';

const stored=new Map<string,string>();
const storage={getItem:(k:string)=>stored.get(k)??null,setItem:(k:string,v:string)=>stored.set(k,v)};
Object.defineProperty(globalThis,'localStorage',{value:storage,configurable:true});
Object.defineProperty(globalThis,'sessionStorage',{value:storage,configurable:true});
let solCallbacks=0;
const callbacks={onSolEnd:()=>{solCallbacks++},onCrisisStart:()=>{},onSound:()=>{}};
const e=new ArtemisEngine(callbacks);
const resources={...e.state.resources};
for(let i=0;i<900;i++)e.step();
assert.deepEqual(e.state.resources,resources,'No resource loss during scientist briefing');
assert.equal(e.state.sol,1);
assert.equal(e.bookMission('moon'),false);
assert.equal(e.acceptInvestment(),true);
assert.equal(e.acceptInvestment(),false,'Investment cannot be collected twice');
assert.equal(e.state.expedition.coins,100);
assert.equal(e.bookMission('mars'),false);
assert.equal(e.state.expedition.coins,100);
assert.equal(e.bookMission('moon'),true);
assert.equal(e.state.expedition.coins,0);
assert.equal(e.bookMission('moon'),false,'No double booking');
assert.equal(e.launchExpedition(),false,'A site must be selected');
assert.equal(e.previewLandingSite('invalid'),false);
assert.equal(e.previewLandingSite('south-polar'),true,'Unaffordable site can be inspected');
assert.equal(e.launchExpedition(),false,'Polar logistics cannot create a negative balance');
assert.equal(e.state.expedition.stage,'landing');
const reload=new ArtemisEngine(callbacks);
assert.equal(reload.loadSavedCampaign(),true);
assert.equal(reload.state.expedition.landingSiteId,'south-polar');
assert.equal(reload.state.expedition.coins,0);
assert.equal(reload.previewLandingSite('equatorial'),true);
assert.equal(reload.launchExpedition(),true);
assert.equal(reload.launchExpedition(),false);
assert.equal(reload.completeLanding(),false,'Cannot land before flight ends');
for(let i=0;i<60;i++)reload.step();
assert.deepEqual(reload.state.resources,resources,'Flight does not run the base economy');
reload.saveCampaign();
const resumed=new ArtemisEngine(callbacks);
assert.ok(resumed.loadSavedCampaign());
assert.ok(resumed.state.expedition.flightElapsedSec>=5);
for(let i=0;i<FLIGHT_DURATION_SEC*10+1;i++)resumed.step();
assert.equal(resumed.completeLanding(),true);
assert.equal(resumed.completeLanding(),false);
assert.equal(resumed.state.expedition.coins,0);
assert.equal(resumed.state.nodes.some(n=>n.type==='ice_crater'),false,'No polar ice deposits placed at equator');
assert.equal(resumed.selectRadiationTerrain('terrain-a'),false,'Polar model must not control equatorial dose');
assert.ok(!('phase' in resumed.state) && !('quests' in resumed.state) && !('quizTotal' in resumed.state));
for(let i=0;i<1000;i++){resumed.state.resources={energy:999,water:999,oxygen:999,food:999,regolith:0};resumed.state.lifeSupportHealth=100;resumed.step()}
assert.equal(resumed.state.tutorial?.step,'base-site','Guided tutorial waits for a location, without quizzes or challenge cards');
assert.deepEqual(resumed.state.activeCards,[]);
resumed.saveCampaign();
const surface=new ArtemisEngine(callbacks);
assert.ok(surface.loadSavedCampaign());assert.equal(surface.state.expedition.stage,'surface');
const damaged=JSON.parse(stored.get(`${SAVE_STORAGE_KEY}_guest`)!);damaged.expedition.coins=-100;
stored.set(`${SAVE_STORAGE_KEY}_guest`,JSON.stringify(damaged));assert.equal(new ArtemisEngine(callbacks).loadSavedCampaign(),false);
resumed.resetMission('campaign','AGAIN');
assert.equal(resumed.state.expedition.stage,'briefing');assert.equal(resumed.state.expedition.coins,0);
const classroom=new ArtemisEngine(callbacks,'classroom','CLASS');
classroom.acceptInvestment();classroom.bookMission('moon');
const classReload=new ArtemisEngine(callbacks);
assert.ok(classReload.loadSavedCampaign('classroom','CLASS'));
assert.equal(classReload.state.expedition.coins,0);
assert.equal(classReload.loadSavedCampaign('classroom','OTHER'),false);
const replay=landOnMoon(new ArtemisEngine(callbacks,'classroom','REPLAY'));
for(let i=0;i<240;i++)replay.step();
replay.saveCampaign();
const replayReload=new ArtemisEngine(callbacks);
assert.ok(replayReload.loadSavedCampaign('classroom','REPLAY'));
for(let i=0;i<440;i++){replay.step();replayReload.step()}
assert.deepEqual(replayReload.state.activeCrisis,replay.state.activeCrisis,'Reload keeps the same seeded event sequence');
assert.deepEqual(replayReload.state.clickableEvents,replay.state.clickableEvents,'Reload keeps drop scheduling and rewards');
assert.deepEqual(replayReload.state.resources,replay.state.resources);
console.log('MISSION TESTS PASSED: funding, prices, site costs, persistence, flight, equatorial resources, no phases or quiz interruptions');
